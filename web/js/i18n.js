    init() {
        const saved = localStorage.getItem('gd_lang');
        if (saved && this.translations[saved]) {
            this.current = saved;
        } else {
            // 跟随浏览器语言
            const lang = navigator.language || 'zh-CN';
            this.current = lang.startsWith('zh') ? 'zh-CN' : 'en';
        }
        this.apply();
    },

    t(key) {
        const dict = this.translations[this.current] || this.translations['zh-CN'];
        return dict[key] || key;
    },

    setLang(lang) {
        if (this.translations[lang]) {
            this.current = lang;
            localStorage.setItem('gd_lang', lang);
            this.apply();
        }
    },

    apply() {
        // 翻译所有带 data-i18n 属性的元素
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            el.textContent = this.t(key);
        });
        // 翻译 placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = this.t(key);
        });
        // 更新语言按钮显示
        const btn = document.getElementById('lang-btn');
        if (btn) {
            btn.textContent = this.current === 'zh-CN' ? '🌐 中' : '🌐 EN';
        }
    },

    toggle() {
        this.setLang(this.current === 'zh-CN' ? 'en' : 'zh-CN');
    }
