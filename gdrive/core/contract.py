# 网盘根路径 —— 与 web 版 VFS 根一致
DRIVE_HOME = '/drive_home'

# base36 字符集 —— 必须与 JS 的 toString(36) 完全一致
_B36_DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def _b36(n):
    """毫秒时间戳转 36 进制 —— 与 JS 的 Date.now().toString(36) 同形

    ★ 这个函数是契约的核心：js 用它生成分片目录名 `mt` + _b36(now)。
      Python 侧只用它来**识别**这类目录（maintain.scan 扫描孤儿），
      不用于生成 —— 生成是 js 的职责。

    ★ 为什么单独留着它：曾经差点随 transfer.py 一起删掉。
      但它是"分片路径命名与 web 版同形"这条契约的唯一可执行验证。
      删了之后，js 改了编码方式 Python 也不会知道。
    """
    if n <= 0:
        return '0'
    out = ''
    while n:
        out = _B36_DIGITS[n % 36] + out
        n //= 36
    return out


def is_chunk_dir(name):
    """判断目录名是否是 js 生成的随机分片目录（形如 mtabc123）"""
    return len(name) > 2 and name.startswith('mt') and all(
        c in _B36_DIGITS for c in name[2:])


